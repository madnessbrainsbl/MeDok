/// Записать строчку в журнал запуска — и в поток ошибок, и в файл рядом с
/// программой (`vypiska-данные/журнал.txt`).
///
/// Зачем файл, если есть терминал: у врача на рабочем месте терминала нет, а
/// когда окно не открывается, сказать по телефону нечего — она видит пустоту.
/// Окном об этом тоже не сообщить: на Linux сообщение рисует та же библиотека,
/// что и диалоги выбора файла, и без обвязки рабочего стола оно просто не
/// появляется. Остаётся файл: врач присылает его целиком, и видно, на каком
/// шаге всё встало.
///
/// Журнал ведётся всегда, отдельного «режима отладки» нет: он нужен ровно
/// тогда, когда что-то пошло не так, а включать его задним числом поздно.
/// Держим два последних запуска (см. `note_new_session`), архив не копим.
/// Персональных данных пациентов сюда не пишем — только техника.
pub fn note(msg: &str) {
    eprintln!("{msg}");
    let _guard = LOG_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    use std::io::Write;
    let path = settings::dir().join("журнал.txt");
    let file = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&path);
    if let Ok(mut f) = file {
        let _ = writeln!(f, "{}  {msg}", fmt::now_hms());
    }
}

/// Начать новый журнал, сохранив предыдущий рядом.
///
/// Месячный архив врачу вести незачем — нужен последний запуск. Но и просто
/// стирать старый нельзя: самый нужный журнал — от запуска, который не
/// открылся, а первое, что делает человек после неудачи, — пробует ещё раз.
/// Второй запуск затирал бы улику. Поэтому предыдущий переезжает в
/// `журнал-прошлый.txt`: под рукой всегда два последних запуска, и больше
/// ничего не копится.
///
/// Отдельным вызовом из `main`, а не «обрезаем при первой записи»: обрезка по
/// первому вызову привязывала журнал к тому, кто позвал раньше. В тестах это
/// значило, что один тест стирает записи другого прямо посреди проверки, —
/// ловилось как плавающее падение. Начинать журнал должен запуск программы,
/// и только он.
pub fn note_new_session() {
    let _guard = LOG_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let dir = settings::dir();
    let now = dir.join("журнал.txt");
    let prev = dir.join("журнал-прошлый.txt");
    let _ = std::fs::remove_file(&prev);
    let _ = std::fs::rename(&now, &prev);
}

/// Найти файл системного шрифта по имени.
///
/// Имя файла у шрифта одно и то же везде (`LiberationSerif-Regular.ttf`,
/// `DejaVuSans.ttf`), а вот каталог у каждого дистрибутива свой:
/// Debian и Ubuntu кладут в `/usr/share/fonts/truetype/…`, а «Альт» и прочие
/// RPM-сборки — в `/usr/share/fonts/ttf/…`. Замерено на живом «Альте» (и 10,
/// и 11): `/usr/share/fonts/ttf/liberation/LiberationSerif-Regular.ttf`.
///
/// Поэтому ищем по имени файла, а не по заранее известному пути: жёстко
/// прописанный каталог промахнулся бы молча — бланк набрался бы запасным
/// шрифтом, а в интерфейсе поехала бы кириллица, и никто бы не понял почему.
#[cfg(unix)]
pub(crate) fn find_font(name: &str) -> Option<std::path::PathBuf> {
    use std::collections::HashMap;
    use std::path::PathBuf;
    use std::sync::OnceLock;

    /// Обход каталогов делаем один раз: `hayro` спрашивает шрифт на каждый
    /// запрос при отрисовке чужого PDF, и ходить по диску каждый раз незачем.
    static INDEX: OnceLock<HashMap<String, PathBuf>> = OnceLock::new();

    fn walk(dir: &std::path::Path, depth: u32, out: &mut HashMap<String, PathBuf>) {
        // Ограничение глубины (вызывается с 4) обязательно: шрифты так
        // глубоко не закапывают, а вот ссылки по кругу и чужие огромные
        // каталоги под /usr/share/fonts встречаются. Проверено симлинком
        // каталога на самого себя и на «/» — обход завершается сразу.
        if depth == 0 {
            return;
        }
        let Ok(rd) = std::fs::read_dir(dir) else {
            return;
        };
        // Обход СТРОГО по алфавиту, а не в том порядке, в каком выдала
        // файловая система. Это не придирка к аккуратности: на «Альте» рядом
        // лежат каталоги `liberation` и `liberation-narrow`, и во втором —
        // СВОИ файлы с теми же именами (сборка 2015 года против 2022-й,
        // контрольные суммы разные). При случайном порядке документ мог
        // набраться то одним шрифтом, то другим, причём незаметно. По
        // алфавиту `liberation` идёт раньше `liberation-narrow`, и правило
        // «первый найденный побеждает» даёт предсказуемый верный выбор.
        let mut entries: Vec<PathBuf> = rd.flatten().map(|e| e.path()).collect();
        entries.sort();
        for path in entries {
            if path.is_dir() {
                walk(&path, depth - 1, out);
            } else if let Some(file) = path.file_name().and_then(|n| n.to_str()) {
                // Первый найденный побеждает: системные каталоги идут раньше
                // пользовательских, и подменять системный шрифт своим не надо.
                out.entry(file.to_string()).or_insert(path.clone());
            }
        }
    }

    let index = INDEX.get_or_init(|| {
        let mut out = HashMap::new();
        let mut roots: Vec<PathBuf> =
            vec!["/usr/share/fonts".into(), "/usr/local/share/fonts".into()];
        if let Ok(home) = std::env::var("HOME") {
            roots.push(PathBuf::from(&home).join(".local/share/fonts"));
            roots.push(PathBuf::from(&home).join(".fonts"));
        }
        for r in roots {
            walk(&r, 4, &mut out);
        }
        out
    });
    index.get(name).cloned()
}

/// На Windows искать нечего: все шрифты лежат в одной системной папке.
#[cfg(windows)]
pub(crate) fn find_font(name: &str) -> Option<std::path::PathBuf> {
    let dir = std::env::var("WINDIR").unwrap_or_else(|_| "C:\\Windows".into());
    let path = std::path::Path::new(&dir).join("Fonts").join(name);
    path.exists().then_some(path)
}
