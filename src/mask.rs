//! Приведение номеров к виду медицинского бланка.
//!
//! Формат жёсткий и одинаковый от пациента к пациенту, поэтому врачу незачем
//! расставлять дефисы руками: он набирает цифры, программа раскладывает.
//! Синтетические примеры формата:
//!   СНИЛС    123-456-789 64
//!   телефон  89000000000
//!   свид-во  III-АА 000001

/// СНИЛС: одиннадцать цифр в виде `XXX-XXX-XXX YY`.
/// Пока цифр меньше — показываем то, что уже набрано, не мешая вводу.
pub fn snils(raw: &str) -> String {
    let d: Vec<char> = raw
        .chars()
        .filter(|c| c.is_ascii_digit())
        .take(11)
        .collect();
    let mut out = String::with_capacity(14);
    for (i, c) in d.iter().enumerate() {
        match i {
            3 | 6 => out.push('-'),
            9 => out.push(' '),
            _ => {}
        }
        out.push(*c);
    }
    out
}

/// Контрольное число СНИЛС. Не блокирует ввод — только подсказывает,
/// что в номере опечатка, пока документ не ушёл в другое учреждение.
pub fn snils_ok(formatted: &str) -> Option<bool> {
    let d: Vec<u32> = formatted.chars().filter_map(|c| c.to_digit(10)).collect();
    if d.len() != 11 {
        return None;
    }
    // Номера до 001-001-998 выдавались без контрольного числа.
    let body: u64 = d[..9].iter().fold(0u64, |a, x| a * 10 + *x as u64);
    if body <= 1_001_998 {
        return Some(true);
    }
    let sum: u32 = d[..9]
        .iter()
        .enumerate()
        .map(|(i, x)| x * (9 - i as u32))
        .sum();
    let control = match sum {
        s if s < 100 => s,
        100 | 101 => 0,
        s => match s % 101 {
            100 | 101 => 0,
            r => r,
        },
    };
    Some(control == d[9] * 10 + d[10])
}

/// Телефон в виде `+7 (900)-000-00-00`.
///
/// Код страны в шаблоне уже стоит, поэтому набранный код страны — ведущая
/// `8`, приставка `+7`, одиннадцатая цифра `7` — из номера убирается: врач
/// набирает как привык, с восьмёрки или с «+7», а в документ уходит единый вид.
pub fn phone(raw: &str) -> String {
    // Приставку «+7» снимаем как приставку, а не как «первую семёрку вообще».
    // Поле возвращает сюда на каждом нажатии своё же отформатированное
    // значение, и без этого «7» из выставленного нами «+7» приходила обратно
    // наравне с набранными цифрами и дописывалась к номеру спереди: три
    // нажатые семёрки показывались как «+7 (777)-77», а «+7999449»
    // превращалось в «+79949449». Считать же кодом страны любую ведущую
    // семёрку нельзя — тогда номер, начинающийся с семёрки, не набрать вовсе:
    // клавиша на вид не срабатывает.
    let rest = raw.strip_prefix("+7").unwrap_or(raw);
    let mut d: Vec<char> = rest.chars().filter(|c| c.is_ascii_digit()).collect();
    match d.first() {
        Some('8') => {
            d.remove(0);
        }
        Some('7') if d.len() == 11 => {
            d.remove(0);
        }
        _ => {}
    }
    d.truncate(10);
    if d.is_empty() {
        // Код страны, набранный руками и ещё не дополненный номером: «+» или
        // «+7». Стереть его на полпути нельзя — следующая цифра встала бы на
        // его место и ушла бы в код города. Всё остальное без цифр (в том
        // числе наш собственный огрызок «+7 (» после стирания последней
        // цифры) поле очищает целиком, чтобы в документ не уехала скобка.
        return match raw {
            "+" | "+7" => raw.to_string(),
            _ => String::new(),
        };
    }
    let mut out = String::from("+7");
    for (i, c) in d.iter().enumerate() {
        match i {
            0 => out.push_str(" ("),
            3 => out.push_str(")-"),
            6 | 8 => out.push('-'),
            _ => {}
        }
        out.push(*c);
    }
    out
}

/// Свидетельство о рождении: римская серия и буквы — прописными.
/// `iii-аа 000001` -> `III-АА 000001`.
pub fn birth_cert(raw: &str) -> String {
    raw.to_uppercase()
}

/// ЧДД и ЧСС: только цифры, не больше трёх. Формата тут нет — это её
/// собственный осмотр, а не номер документа, — но поле то же текстовое,
/// и без фильтра в него подряд вписывались буквы.
pub fn vital(raw: &str) -> String {
    raw.chars().filter(|c| c.is_ascii_digit()).take(3).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn snils_is_formatted() {
        assert_eq!(snils("12345678964"), "123-456-789 64");
        assert_eq!(snils("123-456-789 64"), "123-456-789 64");
        assert_eq!(snils("222 333 444 16"), "222-333-444 16");
        assert_eq!(snils("100000001 10"), "100-000-001 10");
    }

    #[test]
    fn snils_is_formatted_while_typing() {
        assert_eq!(snils(""), "");
        assert_eq!(snils("123"), "123");
        assert_eq!(snils("1234"), "123-4");
        assert_eq!(snils("123456789"), "123-456-789");
        assert_eq!(snils("1234567896"), "123-456-789 6");
        // лишнее отбрасываем, а не уродуем строку
        assert_eq!(snils("123456789649999"), "123-456-789 64");
    }

    /// Синтетические номера с верным контрольным числом обязаны проходить проверку —
    /// иначе подсказка будет кричать на верные данные.
    #[test]
    fn sample_snils_pass_the_checksum() {
        for s in ["123-456-789 64", "222-333-444 16", "100-000-001 10"] {
            assert_eq!(snils_ok(s), Some(true), "{s} должен быть верным");
        }
    }

    #[test]
    fn a_typo_in_snils_is_caught() {
        // переставлены две цифры
        assert_eq!(snils_ok("123-456-798 64"), Some(false));
        // недобранный номер проверять рано
        assert_eq!(snils_ok("123-456-789"), None);
    }

    #[test]
    fn phone_takes_the_single_readable_form() {
        assert_eq!(phone("89000000000"), "+7 (900)-000-00-00");
        assert_eq!(phone("+7 900 000-00-00"), "+7 (900)-000-00-00");
        assert_eq!(phone("79000000000"), "+7 (900)-000-00-00");
        assert_eq!(phone("9000000000"), "+7 (900)-000-00-00");
        assert_eq!(phone("8 (901) 000-00-00"), "+7 (901)-000-00-00");
        // второй синтетический номер
        assert_eq!(phone("89010000000"), "+7 (901)-000-00-00");
    }

    #[test]
    fn phone_is_formatted_while_typing() {
        assert_eq!(phone(""), "");
        assert_eq!(phone("8"), "");
        assert_eq!(phone("890"), "+7 (90");
        assert_eq!(phone("8900"), "+7 (900");
        assert_eq!(phone("89000"), "+7 (900)-0");
        // лишние цифры отбрасываем, а не уродуем строку
        assert_eq!(phone("890000000001234"), "+7 (900)-000-00-00");
    }

    /// Поле отдаёт форматировщику своё же значение на каждом нажатии, поэтому
    /// второй прогон обязан ничего не менять. Пока «7» из выставленного нами
    /// «+7» считалась цифрой номера, код страны прирастал слева на каждом
    /// нажатии — это и есть «набираю +7999449, получается +79949449».
    #[test]
    fn formatting_a_phone_twice_changes_nothing() {
        for s in [
            "",
            "+",
            "+7",
            "9",
            "999",
            "9994",
            "77",
            "89000000000",
            "+7 (900)-000-00-00",
        ] {
            let once = phone(s);
            assert_eq!(phone(&once), once, "повторный прогон {s:?}");
        }
    }

    /// Набранное руками «+7» — код страны, а не первые цифры номера.
    /// Снимается именно приставка: иначе номер, который сам начинается с
    /// семёрки, не набрать вовсе — клавиша на вид не срабатывает.
    #[test]
    fn a_typed_country_code_is_not_part_of_the_number() {
        // дословно то, что она набирает, и что выходило «+79949449»
        assert_eq!(phone("+7999449"), "+7 (999)-449");
        assert_eq!(phone("+79"), "+7 (9");
        // код страны на полпути не стираем — иначе следующая цифра займёт
        // его место и уедет в код города
        assert_eq!(phone("+"), "+");
        assert_eq!(phone("+7"), "+7");
        // а без приставки семёрка — обычная цифра номера
        assert_eq!(phone("7"), "+7 (7");
        assert_eq!(phone("77"), "+7 (77");
        // огрызок без цифр поле очищает целиком
        assert_eq!(phone("+7 ("), "");
    }

    #[test]
    fn birth_cert_series_goes_uppercase() {
        assert_eq!(birth_cert("iii-аа 000001"), "III-АА 000001");
        assert_eq!(birth_cert("IV-АА 000002"), "IV-АА 000002");
    }

    #[test]
    fn vital_keeps_only_digits_capped_at_three() {
        assert_eq!(vital(""), "");
        assert_eq!(vital("19"), "19");
        // буквы не должны попадать в осмотр вовсе, не только визуально
        assert_eq!(vital("авуку"), "");
        assert_eq!(vital("ппппп"), "");
        assert_eq!(vital("1a9b2c"), "192");
        assert_eq!(vital("12345"), "123");
    }
}
